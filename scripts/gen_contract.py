def spec_leaf_paths(s: dict, owner_fields: list[dict], prefix: str) -> list[str]:
    """Every scalar path a document shaped by spec `s` can produce, under `prefix`.

    Walked from the spec rather than typed out, so a field added to a spec is published
    here on the next `make gen` without anyone remembering to. The path shapes mirror what
    the verification command's jq/sed pipeline produces:

      object   -> prefix.field.child           (build_style.planning)
      list of objects -> prefix.field.child    (dimensions.0.score, index stripped mid-path)
      list of scalars -> prefix.field          (tags.0, trailing index stripped)
      map keyed by enum -> one path per key    (no such field today; kept for the next one)
      scalar   -> prefix.field                 (nullable ones included: null is a scalar)
    """

    def walk(fs: list[dict], at: str) -> list[str]:
        out: list[str] = []
        for f in fs:
            path = f"{at}.{f['name']}" if at else f["name"]
            t = f["type"]
            if t == "object" or (t == "list" and f["item"] in s["objects"]):
                out += walk(s["objects"][f["item"]], path)
            elif t == "map":
                out += [f"{path}.{k}" for k in s["enums"][f["key"]]]
            else:
                out.append(path)
        return out

    return walk(owner_fields, prefix)


