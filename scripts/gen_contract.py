import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

# The emitters every spec in this repository shares, so the contract's own objects (v4:
# `burn`, `title_ids`, `call_tokens`) and the `quotes` document are written by the same code
# as the analysis, report and live specs, and `int, nullable` means one thing everywhere.
import gen_analysis as ga  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "privacy" / "upload-contract.json"
