    # `tokens.input` and `strip_marks[].ms` as "sent but not declared". They are not: they
    # are the insides of declared structured fields. But a verification command that cries
    # leak on correct output is worse than none, because the first person to run it
    # publicly concludes the claim is false.
    #
    # `tool_calls` expands to whatever tool names a session used, so it is published as a
    # wildcard with its allowlist stated separately (`tool_call_keys`, v4).
    #
    # `analysis` is the same trap one level deeper (60-odd nested scalar paths) and it is
    # walked from its own spec rather than listed here, because a hand-kept list would be
    # exactly the kind that goes stale the first time the analysis spec grows. `live` and
    # `live_names` are walked from spec/live.v1.json and `burn` and `title_ids` from the
    # contract's own objects, for the same reason.
    nested = {
        "tokens": ["input", "output", "cache_read", "cache_w5m", "cache_w1h"],
        "strip_marks": ["ms", "k"],
        "models": ["model_id", "output_token_share"],
        "feedback": ["id", "seconds", "count"],
        "tool_calls": ["<allowlisted tool name>"],
    }
    os_ = objects_spec(c)
    leaves: list[str] = []
    for f in fields(c):
        if f["name"] in nested:
            leaves += [f"{f['name']}.{child}" for child in nested[f["name"]]]
        elif f["type"] == "analysis":
            leaves += analysis_leaf_paths(f["name"])
        elif f["type"] == "live":
            leaves += live_leaf_paths(f["name"])
        elif f["type"] == "live_names":
            leaves += live_leaf_paths(f["name"], names=True)
        elif f["type"] == "object":
            leaves += spec_leaf_paths(os_, os_["objects"][f["item"]], f["name"])
        else:
            leaves.append(f["name"])

    write(ROOT / "server/builder/media_spec.py", gen_media_py(c))
    write(ROOT / "mobile/src/generated/media.ts", gen_media_ts(c))

    qs = quotes_spec(c)
    ms = media_spec(c)
    media = c["project_media"]
    write(
        ROOT / "server/builder/static/upload-fields.json",
        json.dumps(
            {
                "version": c["version"],
                "fields": sorted(f["name"] for f in fields(c)),
                "leaf_paths": sorted(leaves),
                "tool_call_keys": tool_call_keys(c),
                "documents": {
                    "quotes": {
                        "route": c["quotes"]["route"],
                        "default": c["quotes"]["default"],
                        "leaf_paths": sorted(spec_leaf_paths(qs, qs["fields"], "")),
                    },
                    # One presign per file of a published ship kit, then its document.
                    "ship_kit": {
                        "route": c["ship_kit"]["route"],
                        "document_route": c["ship_kit"]["document_route"],
                        "default": c["ship_kit"]["default"],
                        "leaf_paths": sorted(f["name"] for f in kit_spec()["objects"]["KitPresign"]),
                        "document_leaf_paths": sorted(
                            spec_leaf_paths(kit_spec(), kit_spec()["objects"]["KitDocument"], "")
                        ),
                    },
                    # One presign per file; the bytes follow to the URL it returns.
                    "project_media": {
                        "route": media["route"],
                        "default": media["default"],
                        "leaf_paths": sorted(spec_leaf_paths(ms, ms["fields"], "")),
                        "content_types": media["content_types"],
                        "caps": media["caps"],
                        "max_lengths": media["max_lengths"],
                        "label_rule": media["label_rule"],
                    },
                },
                "note": (
                    "`fields` are the top-level keys. `leaf_paths` expands every structured "
                    "one (tokens, models, strip_marks, feedback, tool_calls, analysis, live, "
                    "live_names, burn, title_ids, call_tokens) so a scalar-path walk of a real payload "
                    "matches exactly, with list indices stripped. tool_calls keys are tool "
                    "names from the fixed allowlist `tool_call_keys`; unknown and MCP tools "
                    "bucket to mcp_other / other. analysis, live_names and the quotes document "
                    "are opt-in; analysis is shaped by spec/analysis.v1.json and live and "
                    "live_names by spec/live.v1.json. `documents` lists what is uploaded "
                    "outside a session payload, each with its own route and leaf paths: the "
                    "quotes document, and `project_media`, the presign that goes before each "
                    "file of a published project demo (the file itself is a PNG, JPEG or MP4 "
                    "of the stated size and nothing else)."
                ),
            },
            indent=2,
        )
        + "\n",
    )
    write(ROOT / "PRIVACY.md", gen_privacy_md(c))


