def ts_value(v, indent: int = 0) -> str:
    """A JSON literal is a TypeScript literal; objects and lists one entry a line."""
    pad = "  " * (indent + 1)
    if isinstance(v, dict):
        if not v:
            return "{}"
        body = ",\n".join(f"{pad}{json.dumps(k)}: {ts_value(x, indent + 1)}" for k, x in v.items())
        return "{\n" + body + ",\n" + "  " * indent + "}"
    if isinstance(v, list) and any(isinstance(x, (dict, list)) for x in v):
        body = ",\n".join(f"{pad}{ts_value(x, indent + 1)}" for x in v)
        return "[\n" + body + ",\n" + "  " * indent + "]"
    return json.dumps(v, ensure_ascii=False)


def gen_ts() -> str:
    parts = [
        BANNER,
        "/**",
        " * Every catalog and template the phone renders from, read out of the engine's own",
        " * tables (docs/overnight-integration.md 1.5). The report and the session upload carry",
        " * ids, numbers and refusal codes; these are the words. Never retype one: change the",
        " * Python table and run `make gen`. `spec/fixtures/wrapped/cards.json` and",
        " * `spec/fixtures/burn/session.json` pin the phone's sentences to Python's.",
        " */",
        "",
    ]
    names = []
    for name, doc, value in tables():
        no_dash(name, value)
        names.append(name)
        parts.append(f"/** {doc} */")
        parts.append(f"export const {name} = {ts_value(value)} as const;")
        parts.append("")
    parts.append("/** Every table above, as one object (`COPY.REFUSALS`, `COPY.TERMS`, ...). */")
    parts.append("export const COPY = {")
    parts.extend(f"  {n}," for n in names)
    parts.append("} as const;")
    return "\n".join(parts) + "\n"


# ---------------------------------------------------------------------------- the cards
def card_entries() -> list[dict]:
    """Every card of every `corpus_fixture.scenarios()` corpus, as the phone gets it (the
    report's `ReportWrappedCard`) beside what Python says about it. A LOCAL card answered
    carries the quote the phone would have (`wrapped.quotes_upload`) and the offset its
    clock is said in; without a quote the phone shows the card as local and says nothing,
    so its display and sentence are null here too. Repeats are dropped."""
    out: list[dict] = []
    seen: set[str] = set()
    for sc in corpus_fixture.scenarios():
        result = wrapped.wrapped(sc.facts, sc.sessions, **sc.kw)
        quotes = {
            q["card"]: q
            for q in wrapped.quotes_upload(result, generated_at=corpus_fixture.T0)["quotes"]
        }
        tz_of = {s.session_id: s.tz_offset_minutes for s in sc.sessions}
        for c in result["cards"]:
            wire_card = report_blocks.wrapped_card(wrapped.wire({"cards": [c], "sample": {}})["cards"][0])
            local = c["id"] in wrapped.LOCAL_CARDS
            quote = quotes.get(c["id"]) if local and c["reason"] is None else None
            answered = c["reason"] is None
            shown = answered and (not local or quote is not None)
            entry = {
                "scenario": sc.name,
                "card": wire_card,
                "quote": quote,
                "tz_offset_minutes": tz_of[result["quotes"][c["id"]]["session_id"]] if quote else None,
                "question": c["question"],
                "display": c["display"] if shown else None,
                "sentence": c["sentence"] if shown else None,
                "refusal": c["reason"],
                "local": local,
            }
            no_dash(f"cards.json {sc.name} {c['id']}", {k: entry[k] for k in ("question", "display", "sentence", "refusal")})
            key = json.dumps({k: v for k, v in entry.items() if k != "scenario"}, sort_keys=True)
            if key not in seen:
                seen.add(key)
                out.append(entry)
    return out


# ---------------------------------------------------------------------------- burn
def burn_entries() -> list[dict]:
    """Each `burn_fixture.scenarios()` session: its harness, the upload's `burn` block, and
    the sentences `burn.explain` says about the same report."""
    out = []
    for s in burn_fixture.scenarios():
        rep = s.report()
        entry = {
            "name": s.name,
            "harness": s.harness,
            "burn": burn.session_wire(rep),
            "sentences": burn.explain(rep),
        }
        no_dash(f"session.json {s.name}", entry["sentences"])
        out.append(entry)
    return out


def project_entries() -> list[dict]:
    """Every `projects_fixture` case beside the words Python says about it."""
    out = projects_fixture.entries()
    for e in out:
        no_dash(f"sentences.json {e['kind']} {e['name']}", {k: e[k] for k in ("sentence", "display", "last") if k in e})
    return out


def dump(obj) -> str:
    return json.dumps(obj, indent=1, ensure_ascii=False) + "\n"


def main() -> None:
    print("gen_copy.py")
    write(COPY_TS, gen_ts())
    write(CARDS_JSON, dump(card_entries()))
    write(BURN_JSON, dump(burn_entries()))
    write(PROJECTS_JSON, dump(project_entries()))
    write(PROJECT_BLOCK_JSON, dump(projects_fixture.block()))
    write(READS_ONLY_JSON, dump(reads_only_fixture.entries()))


if __name__ == "__main__":
    main()
