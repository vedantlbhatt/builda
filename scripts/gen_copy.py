#: No dash in the banner either: the phone's catalog test runs `hasDash` over this whole file.
BANNER = "// GENERATED by scripts/gen_copy.py from the tables in analysis/. DO NOT EDIT."


def write(path: pathlib.Path, text: str) -> None:
    """Write only when the bytes change, so a second `make gen` writes nothing."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == text:
        return
    path.write_text(text)
    print(f"  wrote {path.relative_to(ROOT)}")


def strings(obj):
    if isinstance(obj, str):
        yield obj
    elif isinstance(obj, dict):
        for v in obj.values():
            yield from strings(v)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            yield from strings(v)


def no_dash(where: str, obj) -> None:
    for s in strings(obj):
        if plain.has_dash(s):
            raise SystemExit(f"gen_copy.py: {where} has a dash, which no person may read: {s!r}")


